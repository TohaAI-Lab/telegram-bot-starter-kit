"""Application entry point for the TohaAI Lab Telegram Bot Starter Kit."""

import asyncio
import logging
import sys
from urllib.parse import quote

from aiogram import Bot, Dispatcher
from dotenv import load_dotenv

from config import BASE_DIR, ConfigError, Settings, load_settings
from database.storage import Database
from handlers.commands import create_router
from middlewares.security import AccessMiddleware, ErrorHandlingMiddleware
from services.bot_service import BotService


logger = logging.getLogger(__name__)


class TokenRedactingFormatter(logging.Formatter):
    """Remove the configured token from formatted log records."""

    def __init__(self, token: str) -> None:
        super().__init__("%(asctime)s %(levelname)s %(name)s: %(message)s")
        self._secrets = {token, quote(token, safe="")}
        self._secrets.discard("")

    def format(self, record: logging.LogRecord) -> str:
        text = super().format(record)
        for secret in self._secrets:
            text = text.replace(secret, "[REDACTED]")
        return text


def configure_logging(settings: Settings) -> None:
    handler = logging.StreamHandler()
    handler.setFormatter(TokenRedactingFormatter(settings.bot_token))
    logging.basicConfig(level=settings.log_level, handlers=[handler], force=True)
    # Avoid verbose third-party logging, even in application debug mode.
    for name in ("aiogram", "aiohttp", "asyncio"):
        logging.getLogger(name).setLevel(logging.WARNING)


def create_dispatcher(settings: Settings, service: BotService) -> Dispatcher:
    """Wire command handlers, middleware and dependency injection."""
    dispatcher = Dispatcher(disable_fsm=True, bot_service=service)
    router = create_router()
    # Inner middleware runs only for matched command handlers.
    # Register error handling first so it also catches access-check failures.
    router.message.middleware(ErrorHandlingMiddleware())
    router.message.middleware(AccessMiddleware(settings))
    dispatcher.include_router(router)
    return dispatcher


async def run(settings: Settings) -> None:
    """Initialize storage and run long polling with a managed HTTP session."""
    database = Database(settings.database_path)
    await database.initialize()
    dispatcher = create_dispatcher(settings, BotService(database))

    bot = Bot(token=settings.bot_token)
    try:
        # Polling and webhooks cannot operate together. Never remove a webhook
        # automatically: the operator must deliberately switch delivery modes.
        if (await bot.get_webhook_info()).url:
            logger.error("A webhook is configured. Disable it before using polling.")
            raise ConfigError("Polling requires a bot without an active webhook.")
        logger.info("Starting Telegram long polling")
        await dispatcher.start_polling(
            bot,
            allowed_updates=dispatcher.resolve_used_update_types(),
            close_bot_session=False,
            tasks_concurrency_limit=16,
            tasks_shutdown_timeout=20,
            handle_as_tasks=True,
        )
    finally:
        await bot.session.close()


def main() -> int:
    """Load local configuration and return an appropriate process exit code."""
    try:
        load_dotenv(BASE_DIR / ".env", override=False)
        settings = load_settings()
    except ConfigError as exc:
        # Configuration errors generated by config.py contain no secret values.
        print(f"Configuration error: {exc}", file=sys.stderr)
        return 2
    except Exception as exc:
        print(f"Configuration loading failed ({type(exc).__name__}).", file=sys.stderr)
        return 2

    configure_logging(settings)
    try:
        asyncio.run(run(settings))
    except KeyboardInterrupt:
        logger.info("Stopped by operator")
    except Exception as exc:
        # Do not log raw exception messages or tracebacks at this boundary.
        logger.error("Application stopped (%s)", type(exc).__name__)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
